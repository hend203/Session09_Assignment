using DEPICSharpTask7.Part1;
using DEPICSharpTask7.Part2;
using DEPICSharpTask7.Part5;

namespace Session09_Assignment
{
    internal class Program
    {
        static void Main(string[] args)
        {

            #region Part 1 — Primary Constructor & Records

            // Q2: Two Patient objects with the SAME values
            Patient patient01 = new Patient(1, "Ahmed Ali", "01000000000", "Diabetes");
            Patient patient02 = new Patient(1, "Ahmed Ali", "01000000000", "Diabetes");

            Console.WriteLine(patient01);

            // Q2.1: GetHashCode of both
            Console.WriteLine("patient01 hash: " + patient01.GetHashCode());
            Console.WriteLine("patient02 hash: " + patient02.GetHashCode());
            // Answer: NOT equal. Patient is a CLASS (reference type) and does not override GetHashCode(),
            // so the default implementation is based on the object's identity (its reference in the HEAP),
            // not on its property values. Two different objects => two different hash codes.

            // Q2.2: Equals
            Console.WriteLine("patient01.Equals(patient02): " + patient01.Equals(patient02));
            // Answer: False. Object.Equals() checks REFERENCE equality for classes:
            // "are both variables pointing to the same object?" — here they are two separate objects.

            // Q2.3: Assign patient01 = patient02, then check Equals again
            patient01 = patient02;
            Console.WriteLine("After assignment, Equals: " + patient01.Equals(patient02));
            // Answer: True. Now both variables hold the SAME reference (same object in the HEAP).
            // What changed is not the data, but the identity: patient01 no longer points to its old object.

            // Q3: Two identical PatientDto records
            PatientDto dto01 = new PatientDto(1, "Ahmed Ali", "01000000000");
            PatientDto dto02 = new PatientDto(1, "Ahmed Ali", "01000000000");

            Console.WriteLine(dto01); // records print all their properties automatically
            Console.WriteLine("dto01 hash: " + dto01.GetHashCode());
            Console.WriteLine("dto02 hash: " + dto02.GetHashCode());
            Console.WriteLine("dto01.Equals(dto02): " + dto01.Equals(dto02));
            Console.WriteLine("dto01 == dto02: " + (dto01 == dto02));

            dto01 = dto02;
            Console.WriteLine("After assignment, Equals: " + dto01.Equals(dto02));
            // Difference observed between class and record:
            // - Class (Patient): Equals/GetHashCode use REFERENCE (identity) equality.
            //   Same values but different objects => different hash codes and Equals = False.
            // - Record (PatientDto): Equals/GetHashCode/== use VALUE equality generated by the compiler.
            //   Same values => same hash codes and Equals = True, even for two different objects.
            // - After "dto01 = dto02" nothing changes for the record (still True), because it was already True by value.

            // Q4: Map Patient -> PatientDto and print the result
            PatientDto mappedDto = PatientMapper.MapFromModelToDto(patient01);
            Console.WriteLine(mappedDto);

            #endregion

            #region Part 2 — Singleton

            // Q6: Call GetLogger() four times and print the hash code of each result
            AppLogger logger01 = AppLogger.GetLogger();
            AppLogger logger02 = AppLogger.GetLogger();
            AppLogger logger03 = AppLogger.GetLogger();
            AppLogger logger04 = AppLogger.GetLogger();

            Console.WriteLine(logger01.GetHashCode());
            Console.WriteLine(logger02.GetHashCode());
            Console.WriteLine(logger03.GetHashCode());
            Console.WriteLine(logger04.GetHashCode());
            // Observation: all four hash codes are IDENTICAL.
            // Why: the constructor is private, so the only way to get an AppLogger is GetLogger(),
            // which creates the object only on the first call (when _instance is null) and
            // returns that same stored object on every later call. So all four variables
            // point to ONE single object in the HEAP.

            #endregion

            #region Part 3 — var & dynamic

            // Q7.1: target-typed new (the type is written on the left, "new" infers it)
            Patient p = new(2, "Sara Hassan", "01111111111", "Asthma");

            // Q7.2: var (the type is written on the right, the compiler infers it)
            var patientVar = new Patient(3, "Omar Khaled", "01222222222", "None");

            // Q7.3: dynamic
            dynamic patientDynamic = new Patient(4, "Mona Adel", "01555555555", "Allergy");
            Console.WriteLine(patientDynamic);

            Console.WriteLine(p);
            Console.WriteLine(patientVar);
            // Q7.4: var vs dynamic
            // - var     : type is resolved at COMPILE time. After the first assignment it is fixed
            //             (patientVar is a Patient forever); typos in members are compile errors.
            // - dynamic : type is resolved at RUN time. The variable can hold anything and the compiler
            //             skips checking its members, so a wrong member name (e.g. patientDynamic.Foo())
            //             compiles fine but throws RuntimeBinderException when it runs.

            #endregion

            #region Part 4 — Anonymous Types

            // Q8: two anonymous objects with identical properties and values
            var doctor01 = new { Name = "Sara", Specialty = "Cardiology", ExperienceYears = 8, Salary = 25_000 };
            var doctor02 = new { Name = "Sara", Specialty = "Cardiology", ExperienceYears = 8, Salary = 25_000 };

            Console.WriteLine($"{doctor01.Name} - {doctor01.Specialty}");        // Q8.1
            Console.WriteLine(doctor01.GetHashCode());                            // Q8.2
            Console.WriteLine(doctor02.GetHashCode());                            // Q8.2 (same value as above)
            Console.WriteLine(doctor01.GetType());                                // Q8.3 compiler-generated type name
            Console.WriteLine(doctor01.Equals(doctor02));                         // Q8.4 -> True
            Console.WriteLine(doctor01.ToString());                               // Q8.5 -> { Name = Sara, Specialty = ..., ... }
            // Comparison of equality:
            // - Class (Patient)      : reference equality  -> two objects with same values are NOT equal.
            // - Record (PatientDto)  : value equality      -> same values are equal, and == also works.
            // - Anonymous type       : value equality too (the compiler overrides Equals/GetHashCode/ToString),
            //   as long as both objects have the same property names, types, and order (so they share
            //   ONE compiler-generated type). Anonymous types are immutable, but == is NOT overloaded,
            //   so doctor01 == doctor02 compares references and would be False.

            #endregion

            #region Part 5 — Extension Methods

            // Q10
            Console.WriteLine("Stethoscope".IsShorterThan(5)); // False (length 11 is not < 5)
            Console.WriteLine("Ab".Repeat(4));                 // AbAbAbAb

            #endregion

        }
    }
}
